def run_pacre_vc_scalar_counterexample_receipt() -> dict[str, object]:
    """Reproduce the two frozen v22 cancellation false-rejections."""

    rows: list[dict[str, object]] = []
    for name, common_value, residual_value in (
        PACRE_VC_SCALAR_COUNTEREXAMPLES
    ):
        common = torch.tensor(common_value, dtype=torch.float32)
        residual = torch.tensor(residual_value, dtype=torch.float32)
        specific = (common + residual).contiguous()
        recovered = (specific - common).contiguous()
        error = float((recovered - residual).abs().item())
        tolerance = (
            PACRE_VC_LEGACY_ATOL
            + PACRE_VC_LEGACY_RTOL * abs(float(residual.item()))
        )
        legacy_allclose = bool(
            torch.isclose(
                recovered,
                residual,
                rtol=PACRE_VC_LEGACY_RTOL,
                atol=PACRE_VC_LEGACY_ATOL,
            )
        )
        replay = (common + residual).contiguous()
        exact_forward_replay = (
            tensor_content_fingerprint(replay.reshape(1))
            == tensor_content_fingerprint(specific.reshape(1))
        )

        phase = torch.stack(
            (common + residual, common - residual)
        ).reshape(1, 2, 1, 1, 1).contiguous()
        phase_mean = phase.mean(dim=1, keepdim=True).contiguous()
        phase_residual = (phase - phase_mean).contiguous()
        semantic = phase_roundoff_observations(
            phase,
            phase_mean,
            phase_residual,
        )
        rows.append(
            {
                "name": name,
                "common_hex": float(common.item()).hex(),
                "residual_hex": float(residual.item()).hex(),
                "specific_hex": float(specific.item()).hex(),
                "legacy_recovered_hex": float(recovered.item()).hex(),
                "legacy_absolute_error_hex": error.hex(),
                "legacy_tolerance_hex": tolerance.hex(),
                "legacy_v22_allclose": legacy_allclose,
                "legacy_failure_reproduced": (
                    not legacy_allclose and error > tolerance
                ),
                "same_operand_exact_forward_replay": exact_forward_replay,
                "phase_semantics": semantic.canonical_payload(),
                "inputs": {
                    "common": _tensor_summary(common.reshape(1)),
                    "residual": _tensor_summary(residual.reshape(1)),
                },
            }
        )
    gate_passed = (
        len(rows) == len(PACRE_VC_SCALAR_COUNTEREXAMPLES)
        and all(
            row["legacy_failure_reproduced"] is True
            and row["same_operand_exact_forward_replay"] is True
            and row["phase_semantics"]["passed"] is True
            for row in rows
        )
    )
    body: dict[str, object] = {
        "schema_version": PACRE_VC_SCALAR_COUNTEREXAMPLE_SCHEMA,
        "cases": rows,
        "expected_case_count": 2,
        "observed_case_count": len(rows),
        "legacy_formula_gate_eligible": False,
        "legacy_formula_decision_weight": 0,
        "new_verifier_gate_eligible": True,
        "gate_passed": gate_passed,
        "generated_only": True,
        "dataset_accessed": False,
        "cache_accessed": False,
        "D_R_accessed": False,
        "D_V_accessed": False,
        "D_T_accessed": False,
        "optimizer_constructed": False,
        "training_performed": False,
    }
    return {**body, "receipt_fingerprint": stable_fingerprint(body)}


