"""Generated-only formal-shape numerical evidence for PACRE-VC v23.

Every random input in this module is generated by an independent CPU
``torch.Generator`` and only then copied to the selected device.  Receipts
contain raw-bit fingerprints and scalar summaries, never tensor contents.

The v22 subtractive algebra is replayed only as a zero-decision-weight
attribution ledger.  Gate decisions use exact replay of the operations that
the forward actually executes, analytic FP32 phase bounds, and integrity
checks for the local CPU-FP64 oracle.
"""

